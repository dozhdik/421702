SELECT DISTINCT pg.КодовыйНомерГруппы
FROM ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg
WHERE pg.КодовыйНомерПредмета IN (
	SELECT DISTINCT pg1.КодовыйНомерПредмета
	FROM ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg1
	JOIN СТУДЕНЧЕСКАЯ_ГРУППА AS sg
	ON pg1.КодовыйНомерГруппы = sg.КодовыйНомерГруппы
	WHERE sg.НазваниеГруппы = 'АС-8'
)
GROUP BY pg.КодовыйНомерГруппы
HAVING count(DISTINCT pg.КодовыйНомерПредмета) = (
	SELECT count(DISTINCT pg1.КодовыйНомерПредмета)
	FROM ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg1
	JOIN СТУДЕНЧЕСКАЯ_ГРУППА AS sg
	ON pg1.КодовыйНомерГруппы = sg.КодовыйНомерГруппы
	WHERE sg.НазваниеГруппы = 'АС-8'
)