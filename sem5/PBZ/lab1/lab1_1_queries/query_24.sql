SELECT DISTINCT sg.КодовыйНомерГруппы
FROM СТУДЕНЧЕСКАЯ_ГРУППА AS sg
WHERE sg.КодовыйНомерГруппы NOT IN (
    SELECT DISTINCT pg.КодовыйНомерГруппы
    FROM ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg
    WHERE pg.КодовыйНомерПредмета IN (
        SELECT DISTINCT КодовыйНомерПредмета
        FROM ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg1
        JOIN СТУДЕНЧЕСКАЯ_ГРУППА AS sg1
        ON pg1.КодовыйНомерГруппы = sg1.КодовыйНомерГруппы
        WHERE sg1.НазваниеГруппы = 'АС-8'
    )
)