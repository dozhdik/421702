SELECT DISTINCT pg.НомерАудитории, sg.НазваниеГруппы, pr.НазваниеПредмета
FROM ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg
JOIN СТУДЕНЧЕСКАЯ_ГРУППА AS sg
ON pg.КодовыйНомерГруппы = sg.КодовыйНомерГруппы
JOIN ПРЕДМЕТ AS pr
ON pg.КодовыйНомерПредмета = pr.КодовыйНомер
WHERE pg.НомерАудитории BETWEEN 100 AND 200