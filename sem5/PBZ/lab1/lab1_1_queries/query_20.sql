SELECT DISTINCT prep.ЛичныйНомер, prep.Фамилия
FROM ПРЕПОДАВАТЕЛЬ AS prep
JOIN ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg
ON prep.ЛичныйНомер = pg.ЛичныйНомер
JOIN СТУДЕНЧЕСКАЯ_ГРУППА AS sg
ON pg.КодовыйНомерГруппы = sg.КодовыйНомерГруппы
JOIN ПРЕДМЕТ AS pred
ON pg.КодовыйНомерПредмета = pred.КодовыйНомер
WHERE prep.Кафедра = 'ЭВМ'
AND sg.Специальность = pred.Специальность 