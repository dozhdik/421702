SELECT DISTINCT pg.ЛичныйНомер
FROM ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg
JOIN СТУДЕНЧЕСКАЯ_ГРУППА AS sg
ON pg.КодовыйНомерГруппы = sg.КодовыйНомерГруппы
WHERE sg.НазваниеГруппы = 'Э-15' AND pg.ЛичныйНомер NOT IN (
	SELECT pg1.ЛичныйНомер
	FROM ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg1
	WHERE pg1.КодовыйНомерПредмета = '12П'
)	