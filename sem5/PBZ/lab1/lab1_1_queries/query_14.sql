SELECT DISTINCT prep.Фамилия
FROM ПРЕПОДАВАТЕЛЬ AS prep
JOIN ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg1
ON prep.ЛичныйНомер = pg1.ЛичныйНомер
WHERE pg1.КодовыйНомерПредмета IN (
    SELECT DISTINCT pg2.КодовыйНомерПредмета
    FROM ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg2
    WHERE pg2.ЛичныйНомер IN (
        SELECT DISTINCT pg3.ЛичныйНомер
        FROM ПРЕПОДАВАТЕЛЬ_ПРЕПОДАЕТ_ПРЕДМЕТЫ_В_ГРУППАХ AS pg3
        WHERE pg3.КодовыйНомерПредмета = '14П'
    )
);