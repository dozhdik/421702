% ============================================================
% ЗАДАЧА "ОБЕЗЬЯНА И БАНАН"
% Простое решение на чистом Prolog (SWI-Prolog)
% Поиск в ширину (BFS)
% ============================================================
%
% ЗАДАЧА:
%   Обезьяна должна достать банан. Для этого нужно:
%   1. Взять палку
%   2. Пододвинуть ящик под банан
%   3. Залезть на ящик
%   4. Сбить банан палкой
%
% ЗАПУСК:
%   swipl monkey.pl -g "go, halt."
%
% ИНТЕРАКТИВНЫЙ РЕЖИМ:
%   swipl monkey.pl
%   ?- solve(Actions).
%   ?- print_actions(Actions).
% ============================================================

% ============================================================
% БЛОК 1: ГЕОМЕТРИЯ КЛЕТКИ
% ============================================================

% Размер клетки 5x5 (можно изменить)
size(5).

% Проверка: координата в пределах клетки
valid([X, Y]) :- size(S), X >= 1, X =< S, Y >= 1, Y =< S.

% Шаг в направлении (смещение координат)
step([X, Y], up,    [X, Y2]) :- Y2 is Y + 1.   % Вверх: Y + 1
step([X, Y], down,  [X, Y2]) :- Y2 is Y - 1.   % Вниз: Y - 1
step([X, Y], left,  [X2, Y]) :- X2 is X - 1.   % Влево: X - 1
step([X, Y], right, [X2, Y]) :- X2 is X + 1.   % Вправо: X + 1

% Все направления движения
dir(up). dir(down). dir(left). dir(right).

% Клетки рядом (включая одну и ту же)
adjacent([X, Y], [X, Y]).
adjacent([X1, Y], [X2, Y]) :- abs(X1-X2, 1).
adjacent([X, Y1], [X, Y2]) :- abs(Y1-Y2, 1).

% ============================================================
% БЛОК 2: СОСТОЯНИЕ МИРА
% ============================================================
%
% Структура: state(Обезьяна, Ящик, ПалкаВРуке, НаЯщике, БананДобыт)
%
%   Обезьяна    — [X, Y] координаты обезьяны
%   Ящик       — [X, Y] координаты ящика
%   ПалкаВРуке — yes/no (взяла ли обезьяна палку)
%   НаЯщике    — yes/no (на ящике ли обезьяна)
%   БананДобыт — yes/no (добыт ли банан)
%
% Фиксированные позиции предметов:
banana_pos([3, 4]).  % Банан висит по центру
stick_pos([4, 1]).    % Палка лежит в углу

% Начальное состояние (задаётся явно):
%   Обезьяна в [1,1], ящик в [2,2], палка не взята, не на ящике, банан не добыт
init(state([1, 1], [2, 2], no, no, no)).

% Цель: палка в руке, банан добыт (неважно где обезьяна и ящик)
goal(state(_, _, yes, _, yes)).

% ============================================================
% БЛОК 3: ПЕРЕХОДЫ МЕЖДУ СОСТОЯНИЯМИ
% ============================================================
%
% Каждое действие — это переход из одного состояния в другое.
% Формат: trans(ТекущееСостояние, Действие, НовоеСостояние)
%
% Все действия:
%   - move(D, Pos)    — движение в направлении D, оказались в Pos
%   - push(D, B2, M2) — толкнули ящик, он стал в B2, обезьяна в M2
%   - grab            — взяли палку
%   - climb           — залезли на ящик
%   - jump(D, M2)     — спрыгнули с ящика в направлении D
%   - hit             — сбили банан
% ============================================================

% 1. ДВИЖЕНИЕ (когда не на ящике)
% Условие: двигаемся в свободную клетку (не на ящик)
trans(state(M, B, S, no, G), move(D, M2), state(M2, B, S, no, G)) :-
    dir(D),              % Перебираем направления
    step(M, D, M2),      % Следующая позиция
    valid(M2),           % В пределах клетки
    M2 \= B.             % Не на ящике

% 2. ТОЛКАНИЕ ЯЩИКА
% Условие: обезьяна стоит ЗА ящиком (в клетке, куда ящик будет двигаться)
trans(state(M, B, S, no, G), push(D, B2, M2), state(M2, B2, S, no, G)) :-
    dir(D),              % Направление толкания
    step(B, D, B2),      % Ящик двигается в B2
    valid(B2),           % B2 допустима
    step(B2, D, M2),     % Обезьяна оказывается там, где был ящик
    valid(M2),           % M2 допустима
    M = B2.              % Обезьяна была за ящиком

% 3. ВЗЯТЬ ПАЛКУ
% Условие: обезьяна на той же клетке, где лежит палка
trans(state(P, B, no, no, G), grab, state(P, B, yes, no, G)) :-
    stick_pos(P).

% 4. ЗАЛЕЗТЬ НА ЯЩИК
% Условие: обезьяна рядом с ящиком (и не на нём)
trans(state(M, B, S, no, G), climb, state(B, B, S, yes, G)) :-
    adjacent(M, B).

% 5. СПРЫГНУТЬ С ЯЩИКА
% Условие: обезьяна на ящике
trans(state(B, B, S, yes, G), jump(D, M2), state(M2, B, S, no, G)) :-
    dir(D),
    step(B, D, M2),      % Прыгаем в соседнюю клетку
    valid(M2).

% 6. СБИТЬ БАНАН
% Условие: обезьяна на ящике, есть палка, ящик под бананом
trans(state(B, B, yes, yes, no), hit, state(B, B, yes, yes, yes)) :-
    banana_pos(B).

% ============================================================
% БЛОК 4: ПОИСК РЕШЕНИЯ (BFS)
% ============================================================
%
% BFS (поиск в ширину) гарантирует кратчайший путь.
%
% Очередь: [[Состояние, ПутьКНему], ...]
%
% Алгоритм:
%   1. Взять голову очереди
%   2. Если это цель — успех!
%   3. Иначе — добавить все новые состояния в хвост очереди
%   4. Повторять, пока очередь не пуста
% ============================================================

% Точка входа: запускаем BFS с начальным состоянием
solve(Actions) :-
    init(Start),
    bfs([[Start, []]], [], Actions).

% Базовый случай: голова очереди — цель
bfs([[State, Path]|_], _, Path) :-
    goal(State), !.

% Рекурсивный случай: обрабатываем голову
bfs([[State, Path]|Tail], Visited, Solution) :-
    % Находим все возможные переходы из текущего состояния
    findall([Next, [Action|Path]],
            (trans(State, Action, Next),        % Есть переход
             \+ member_state(Next, Visited)),   % Ещё не были
            NewStates),
    % Добавляем новые состояния в конец очереди
    append(Tail, NewStates, Queue2),
    % Рекурсивно обрабатываем дальше
    bfs(Queue2, [State|Visited], Solution).

% Проверка: было ли такое состояние?
% Используем == для точного сравнения (не унификацию!)
member_state(S, [H|_]) :- S == H, !.
member_state(S, [_|T]) :- member_state(S, T).

% ============================================================
% БЛОК 5: ВЫВОД РЕЗУЛЬТАТА
% ============================================================

% Печать пустого списка
print_actions([]).

% Печать действия и рекурсия для хвоста
print_actions([A|R]) :-
    write('  '), write(A), nl,
    print_actions(R).

% Главная точка входа
go :-
    write('========================================'), nl,
    write('  ЗАДАЧА: ОБЕЗЬЯНА И БАНАН'), nl,
    write('========================================'), nl, nl,
    write('Начальная позиция: обезьяна [1,1], ящик [2,2]'), nl,
    write('Цель: взять палку [4,1], достать банан [3,4]'), nl, nl,
    (solve(Actions) ->
        write('РЕШЕНИЕ НАЙДЕНО:'), nl,
        print_actions(Actions),
        nl, write('БАКУ! Банан добыт!'), nl
    ;
        write('Решение не найдено.'), nl
    ).